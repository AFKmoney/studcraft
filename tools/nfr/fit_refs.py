#!/usr/bin/env python3
"""Fit the StudCraft reference photos (refs/*.jpg, NOT committed) into tiny SIRENs
(NFR method, skills-nfr/nfr-srn) and write src/game/nfrFields.ts: int8 per-block
weights (first layer fp16-rounded), evaluated by the SNR shader. No raster ships.
Luminance fields are mean-normalised (detail around 1.0) so they recolour with any palette."""
import json, math, sys
import numpy as np
from PIL import Image
sys.path.insert(0, ".")
from siren_fit import init, forward, backward, psnr, quantize_block_int8

REFS = "../../refs/"
FIELDS = {  # name: (file, crop box, channels, size, hidden)
    "bombe": ("bombe.jpg", (560, 250, 700, 640), 1, 64, 24),     # barrel side: two black bands, specular sheen
    "demoule": ("demoule.jpg", (380, 360, 620, 600), 1, 64, 48),  # v3: tight chest crop — stacked greeble bricks + hairline cracks
    "dragon": ("dragon.jpg", (120, 90, 340, 280), 3, 64, 44),     # v3: trans-purple truss panel, wider net
    "crab": ("collection.jpg", (80, 300, 260, 420), 1, 64, 24),   # studded red shell shading
}
STEPS = int(sys.argv[1]) if len(sys.argv) > 1 else 2500
out, report = {}, {}
for name, (f, box, ch, n, hid) in FIELDS.items():
    im = np.asarray(Image.open(REFS + f).convert("RGB").crop(box).resize((n, n), Image.LANCZOS), dtype=np.float64) / 255
    if ch == 1:
        lum = im @ np.array([0.299, 0.587, 0.114])
        Y = (lum / lum.mean() * 0.5).reshape(-1, 1)  # 0.5 = mean → shader scales by 2
    else:
        Y = im.reshape(-1, 3)
    lin = np.linspace(-1, 1, n)
    X = np.stack(np.meshgrid(lin, -lin), -1).reshape(-1, 2)  # +y up
    rng = np.random.default_rng(1)
    P = init([2, hid, hid, ch], rng)
    m = [[np.zeros_like(p) for p in L] for L in P]; v = [[np.zeros_like(p) for p in L] for L in P]
    for s in range(1, STEPS + 1):
        o, A, Z = forward(P, X)
        G = backward(P, A, Z, 2 * (o - Y) / len(X))
        lr = 1e-3 * (0.3 if s > STEPS * 0.7 else 1)
        for li, L in enumerate(P):
            for pi in range(2):
                g = G[li][pi]; m[li][pi] = .9 * m[li][pi] + .1 * g; v[li][pi] = .999 * v[li][pi] + .001 * g * g
                L[pi] -= lr * (m[li][pi] / (1 - .9 ** s)) / (np.sqrt(v[li][pi] / (1 - .999 ** s)) + 1e-8)
    o, _, _ = forward(P, X)
    layers, Q, nbytes = [], [], 0
    for i, (W, b) in enumerate(P):
        if i == 0:
            Wd = W.astype(np.float16).astype(np.float64)
            layers.append({"w": [round(float(x), 5) for x in Wd.T.ravel()], "b": [round(float(x), 5) for x in b.astype(np.float16)]})
            Q.append([Wd, b.astype(np.float16).astype(np.float64)]); nbytes += (W.size + b.size) * 2
        else:
            flat = W.T.ravel(); pad = (-len(flat)) % 64
            fb = np.concatenate([flat, np.zeros(pad)]).reshape(-1, 64)
            sc = np.abs(fb).max(1, keepdims=True) / 127; sc[sc == 0] = 1
            q = np.round(fb / sc).astype(np.int8)
            deq = (q * sc).ravel()[: len(flat)].reshape(W.T.shape).T
            layers.append({"q": q.ravel()[: len(flat)].tolist(), "s": [float(np.float16(x)) for x in sc.ravel()], "b": [round(float(x), 5) for x in b.astype(np.float16)]})
            Q.append([deq, b.astype(np.float16).astype(np.float64)]); nbytes += q.size + sc.size * 2 + b.size * 2
    oq, _, _ = forward(Q, X)
    report[name] = {"crop": f"{f} {box}", "grid": n, "net": f"2-{hid}-{hid}-{ch}", "params": int(sum(W.size + b.size for W, b in P)),
                    "bytes_int8": int(nbytes), "pixels_bytes": n * n * ch, "psnr_fp32": round(psnr(o, Y), 2), "psnr_int8": round(psnr(oq, Y), 2)}
    out[name] = {"ch": ch, "hidden": hid, "layers": layers}
    Image.fromarray((np.clip(oq.reshape(n, n, ch).squeeze() * (2 if ch == 1 else 1) * (1 if ch == 3 else 127.5), 0, 255)).astype(np.uint8) if ch == 1 else (np.clip(oq.reshape(n, n, 3), 0, 1) * 255).astype(np.uint8)).resize((256, 256)).save(f"/tmp/nfr/fit-{name}.png")
    print(name, report[name], flush=True)
ts = ("// GENERATED by tools/nfr/fit_refs.py — NFR/SIREN fields fitted on refs/*.jpg (photos are NOT shipped).\n"
      "// Each field is f(x,y) = W3·sin(30(W2·sin(30(W1·p+b1))+b2))+b3; layer 1 fp16, layers 2-3 int8 per-block (64) + fp16 scales.\n"
      f"export const NFR_REPORT = {json.dumps(report)} as const;\n"
      f"export const NFR_FIELDS: Record<string, NfrField> = {json.dumps(out, separators=(',', ':'))};\n"
      "export type NfrLayer = { w?: number[]; q?: number[]; s?: number[]; b: number[] };\n"
      "export type NfrField = { ch: number; hidden: number; layers: NfrLayer[] };\n")
open("../../src/game/nfrFields.ts", "w").write(ts)
print("wrote nfrFields.ts", len(ts), "chars")
